def generator():
#Начинаем с числа 2
    n = 2  
    
    while True:
#Предполагаем что число простое пока не докажем обратное
        is_prime = True
#Проверяем делители от 2 до квадратного корня из n
        for i in range(2, int(n ** 0.5) + 1):
#Если n делится на i без остатка           
            if n % i == 0:
#Число составное                      
                is_prime = False
                break
#Если число простое - возвращаем его через yield
        if is_prime:
            yield n
#Переходим к следующему числу для проверки
        n += 1

print("простые числа:")
gen = generator()
#Получаем и выводим первые 40 простых чисел
for _ in range(40):
#next() запрашивает следующее значение
    print(next(gen))  